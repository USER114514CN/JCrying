package com.user114514.encryptor.excep;

public class IllegalManifestException extends Exception {
    public IllegalManifestException() { super(); }
    public IllegalManifestException(String msg) { super(msg); }
    public IllegalManifestException(String msg, Throwable cause) { super(msg, cause); }
    public IllegalManifestException(Throwable cause) { super(cause); }
}
